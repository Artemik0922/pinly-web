export const CATEGORY_BY_SLUG: Record<string, CategoryPage> = Object.fromEntries(
  CATEGORY_PAGES.map((page) => [page.slug, page]),
);

export const CATEGORY_BY_NAME: Record<string, CategoryPage> = Object.fromEntries(
  CATEGORY_PAGES.map((page) => [page.name, page]),
);

export function slugToCategory(slug: string): CategoryPage | undefined {
  return CATEGORY_BY_SLUG[slug];
}

// Чистый URL категории; для неизвестного имени остаётся старый query-путь,
// чтобы ссылка не превращалась в 404.
export function categoryHref(name?: string): string {
  const page = name ? CATEGORY_BY_NAME[name] : undefined;
  return page ? `/category/${page.slug}` : `/?category=${encodeURIComponent(name ?? "")}`;
}
